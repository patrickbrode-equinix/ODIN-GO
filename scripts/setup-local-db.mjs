import crypto from "node:crypto";
import fs from "node:fs/promises";
import path from "node:path";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const rootDir = path.resolve(scriptDir, "..");
const backendDir = path.join(rootDir, "Backend");
const backendEnvPath = path.join(backendDir, ".env");
const requireFromBackend = createRequire(path.join(backendDir, "package.json"));
const { Client } = requireFromBackend("pg");

const DATABASE_NAME = "shiftplanner";
const DATABASE_USER = "shiftplanner_app";
const LOCAL_HOSTS = new Set(["localhost", "127.0.0.1", "::1"]);

function parseEnv(content) {
  const values = {};
  for (const rawLine of content.split(/\r?\n/)) {
    const line = rawLine.trim();
    if (!line || line.startsWith("#")) continue;
    const separator = line.indexOf("=");
    if (separator < 1) continue;
    values[line.slice(0, separator).trim()] = line.slice(separator + 1).trim().replace(/^['"]|['"]$/g, "");
  }
  return values;
}

function loadAdminConfig(env) {
  if (env.DATABASE_URL) {
    const url = new URL(env.DATABASE_URL);
    return {
      host: url.hostname,
      port: Number(url.port || 5432),
      user: decodeURIComponent(url.username),
      password: decodeURIComponent(url.password),
    };
  }

  return {
    host: env.DB_HOST || "localhost",
    port: Number(env.DB_PORT || 5432),
    user: env.DB_USER || "postgres",
    password: env.DB_PASSWORD,
  };
}

let existingEnv;
try {
  existingEnv = parseEnv(await fs.readFile(backendEnvPath, "utf8"));
} catch {
  throw new Error("Backend/.env fehlt. Fuer die einmalige Einrichtung werden lokale PostgreSQL-Adminzugangsdaten benoetigt.");
}

if (existingEnv.DB_NAME === DATABASE_NAME && existingEnv.DB_USER === DATABASE_USER) {
  const additions = [];
  if (!existingEnv.SHIFTPLANNER_API_KEY) {
    const applicationKey = crypto.randomBytes(48).toString("hex");
    additions.push(`SHIFTPLANNER_API_KEY=${applicationKey}`);
  }
  if (!existingEnv.SHIFTPLANNER_ADMIN_PASSWORD) {
    additions.push("SHIFTPLANNER_ADMIN_PASSWORD=root");
  }
  if (additions.length > 0) {
    await fs.appendFile(backendEnvPath, `${additions.join("\n")}\n`, "utf8");
    console.log("[Schichtplaner] Interne App- und Admin-Konfiguration wurde ergaenzt.");
  } else {
    console.log("[Schichtplaner] Die unabhaengige Datenbank ist bereits eingerichtet.");
  }
  process.exit(0);
}

const admin = loadAdminConfig(existingEnv);
if (!LOCAL_HOSTS.has(admin.host)) {
  throw new Error(`Sicherheitsabbruch: Datenbanken duerfen nur auf dem lokalen Rechner eingerichtet werden (gefunden: ${admin.host}).`);
}
if (!admin.password) {
  throw new Error("DB_PASSWORD fehlt. Die neue lokale Datenbank kann nicht eingerichtet werden.");
}

const databasePassword = crypto.randomBytes(32).toString("hex");
const jwtSecret = crypto.randomBytes(48).toString("hex");
const applicationKey = crypto.randomBytes(48).toString("hex");
const client = new Client({
  host: admin.host,
  port: admin.port,
  database: "postgres",
  user: admin.user,
  password: admin.password,
  connectionTimeoutMillis: 5000,
});

await client.connect();
try {
  const role = await client.query("SELECT 1 FROM pg_roles WHERE rolname = $1", [DATABASE_USER]);
  if (role.rowCount === 0) {
    await client.query(`CREATE ROLE ${DATABASE_USER} WITH LOGIN PASSWORD '${databasePassword}'`);
  } else {
    await client.query(`ALTER ROLE ${DATABASE_USER} WITH LOGIN PASSWORD '${databasePassword}'`);
  }

  const database = await client.query("SELECT 1 FROM pg_database WHERE datname = $1", [DATABASE_NAME]);
  if (database.rowCount === 0) {
    await client.query(`CREATE DATABASE ${DATABASE_NAME} OWNER ${DATABASE_USER}`);
  } else {
    await client.query(`ALTER DATABASE ${DATABASE_NAME} OWNER TO ${DATABASE_USER}`);
  }

  await client.query(`REVOKE CONNECT ON DATABASE ${DATABASE_NAME} FROM PUBLIC`);
  await client.query(`GRANT CONNECT ON DATABASE ${DATABASE_NAME} TO ${DATABASE_USER}`);
} finally {
  await client.end();
}

const standaloneEnv = [
  "# Standalone Schichtplaner - generated by npm run setup",
  "PORT=5055",
  "NODE_ENV=development",
  "APP_MODE=shiftplanner",
  "",
  `DB_HOST=${admin.host}`,
  `DB_PORT=${admin.port}`,
  `DB_NAME=${DATABASE_NAME}`,
  `DB_USER=${DATABASE_USER}`,
  `DB_PASSWORD=${databasePassword}`,
  "",
  `JWT_SECRET=${jwtSecret}`,
  `SHIFTPLANNER_API_KEY=${applicationKey}`,
  "SHIFTPLANNER_ADMIN_PASSWORD=root",
  "JWT_EXPIRES_IN=8h",
  "CORS_ORIGINS=http://localhost:5173,http://127.0.0.1:5173",
  "TEAMS_CHANNEL_WEBHOOK=",
  "TEAMS_PERSONAL_WEBHOOK=",
  "",
].join("\n");

await fs.writeFile(backendEnvPath, standaloneEnv, { encoding: "utf8", mode: 0o600 });
console.log(`[Schichtplaner] Neue lokale Datenbank '${DATABASE_NAME}' und Benutzer '${DATABASE_USER}' wurden eingerichtet.`);
console.log("[Schichtplaner] Die ODIN-Datenbank wird von dieser Anwendung nicht verwendet.");
